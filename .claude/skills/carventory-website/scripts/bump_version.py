#!/usr/bin/env python3
"""Bump the cache-busting ?v= version on style.css and script.js in index.html.

New version is today's date (YYYY-MM-DD). If the current version is already
today or later (e.g. a teammate's clock was ahead), it becomes <that date>.2,
.3, ... so the version never goes backwards to a value browsers may have cached. Pass an explicit version to override:

    python3 -I .claude/skills/carventory-website/scripts/bump_version.py
    python3 -I .claude/skills/carventory-website/scripts/bump_version.py 2026-12-01
"""
import datetime
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
INDEX = ROOT / "index.html"
# The legal pages (generated by tools/sync_legal.py) and the vehicle type pages load the same
# stylesheet, so they share the version
PAGES = [INDEX] + [ROOT / p for p in ("privacy/index.html", "terms/index.html", "terms/business/index.html")
                   if (ROOT / p).exists()] + sorted(ROOT.glob("vehicles/*/index.html"))
PATTERN = re.compile(r'((?:style\.css|script\.js|legal\.js|vehicle\.js)\?v=)([^"]+)(")')

html = INDEX.read_text(encoding="utf-8")
current = {m.group(2) for m in PATTERN.finditer(html)}
if not current:
    sys.exit("index.html: no ?v= found on style.css / script.js")
old = sorted(current)[-1]

if len(sys.argv) > 1:
    new = sys.argv[1]
else:
    # Never go backwards: an older value may still be cached by browsers.
    today = datetime.date.today().isoformat()
    m = re.fullmatch(r"(\d{4}-\d{2}-\d{2})(?:\.(\d+))?", old)
    old_date, old_n = (m.group(1), int(m.group(2) or 1)) if m else ("", 0)
    if today > old_date:
        new = today
    else:
        new = f"{old_date}.{old_n + 1}"

count = 0
for page in PAGES:
    text, n = PATTERN.subn(lambda m: m.group(1) + new + m.group(3), page.read_text(encoding="utf-8"))
    page.write_text(text, encoding="utf-8")
    count += n
print(f"?v= {old} -> {new} ({count} references in {len(PAGES)} pages)")
